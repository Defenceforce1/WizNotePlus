// A query (not a fragment) distinguishes repeated loads of the same local file.
// No stored-note rewrite, credential or account data is put in this URL.
inline QUrl navigationUrl(QUrl local)
{
    if (!local.isLocalFile()) return {};
    QUrlQuery query(local);
    query.removeAllQueryItems("wiz-document-load");
    query.addQueryItem("wiz-document-load", QUuid::createUuid().toString(QUuid::WithoutBraces));
    local.setQuery(query);
    return local;
}
inline QString documentExpression(const QUrl& expected)
{
    const QString literal = QString::fromUtf8(QJsonDocument(QJsonArray{expected.toString(QUrl::FullyEncoded)}).toJson(QJsonDocument::Compact));
    return "(()=>{try{const actual=new URL(location.href);actual.hash='';"
        "return actual.href!=="+literal+"[0]?'failed':document.readyState==='complete'?'ready':'pending';}catch(e){return 'failed';}})()";
}
// Paths and account display names are data, not JavaScript source. This also
// preserves quotes, backslashes, line breaks and non-ASCII aliases verbatim.
inline QString initializeEditorScript(const QString& path, const QString& language,
                                     const QString& guid, const QString& alias,
                                     bool ignoreTable, const QString& noteType)
{
    const QJsonArray args{path,language,guid,alias,ignoreTable,noteType,false};
    return "await WizEditorInit(..."+QString::fromUtf8(QJsonDocument(args).toJson(QJsonDocument::Compact))+");";
}
// tokenLiteral is a JSON string literal generated by the caller, never raw
// note text. The wrapper is shared with the native delayed-Promise regression.
inline QString setupScript(const QString& tokenLiteral, const QString& body)
{
    return "window.WizNativeEditorSetup={token:"+tokenLiteral+",state:'pending'};\n"
        "(async function(){try{\n"+body+"\n"
        "if(window.WizNativeEditorSetup.token!=="+tokenLiteral+")return;"
        "WizNativeEditorSetup.state='ready';"
        // Presentation can observe completion immediately; the existing native
        // readiness watcher remains authoritative. A listener failure must not
        // turn successful editor setup into a failed initialization.
        "try{window.dispatchEvent(new Event('wiz-native-editor-setup-state'));}catch(_){}"
        "}catch(error){if(window.WizNativeEditorSetup.token==="+tokenLiteral+")"
        "{WizNativeEditorSetup.state='failed';"
        "try{window.dispatchEvent(new Event('wiz-native-editor-setup-state'));}catch(_){}}"
        "console.error('Editor setup failed',error);}})();";
}
inline QString stateExpression(const QString& tokenLiteral)
{
    return "window.WizNativeEditorSetup&&WizNativeEditorSetup.token==="+tokenLiteral
        +"?WizNativeEditorSetup.state:'failed'";
}
// runJavaScript does not await a returned Promise. Observe an explicit JS
// setup state instead. Only one query may be in flight; timeout and owner
// cancellation also work when a renderer never completes that query.
inline void watch(QObject* owner, QWebEnginePage* page, const QString& expression,
                  std::function<bool()> current, std::function<void(bool)> finished,
                  int timeoutMs = 30000)
{
    if(!owner||!page||!current||!finished)return;
    const QPointer<QObject> context(owner);
    const QPointer<QWebEnginePage> target(page);
    const auto allowed=[context,current] {
        if(!context)return false;
        const bool valid=current();
        return valid&&context;
    };
    if(!allowed()||!target)return;
    struct State { bool done=false; bool inFlight=false; QElapsedTimer elapsed; };
    const auto state=std::make_shared<State>();state->elapsed.start();
    const QPointer<QTimer> timer(new QTimer(context));
    const auto complete=[state,target,timer,allowed,finished](bool ready) {
        if(state->done)return;
        state->done=true;
        if(timer){timer->stop();timer->deleteLater();}
        if(allowed())finished(ready&&bool(target));
    };
    QObject::connect(timer.data(),&QTimer::timeout,owner,
        [state,target,expression,allowed,complete,timeoutMs] {
        if(state->done)return;
        const bool permitted=allowed();
        if(state->done)return;
        if(!target||!permitted){complete(false);return;}
        if(state->elapsed.elapsed()>=timeoutMs){complete(false);return;}
        if(state->inFlight)return;
        state->inFlight=true;
        target->runJavaScript(expression,[state,target,allowed,complete](const QVariant& value){
            if(state->done)return;
            state->inFlight=false;
            const bool permitted=allowed();
            if(state->done)return;
            if(!target||!permitted){complete(false);return;}
            if(value.userType()!=QMetaType::QString||value.toString()=="failed")complete(false);
            else if(value.toString()=="ready")complete(true);
        });
    });
    timer->start(25);
}
